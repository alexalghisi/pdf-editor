// Regenerates the TypeScript module that carries the Unicode fallback font.
// The font is a subset of Liberation Sans (SIL Open Font License 1.1),
// metric-compatible with Arial/Helvetica, covering Latin (incl. Romanian
// ș ț ă), Greek and Cyrillic. Edited text a PDF's own font cannot show is
// written with it.
const fs = require('fs');
const path = require('path');

const source = path.join(
  __dirname,
  '..',
  'assets',
  'fonts',
  'LiberationSans-Subset.ttf',
);
const target = path.join(
  __dirname,
  '..',
  'src',
  'infrastructure',
  'pdf',
  'fonts',
  'unicodeFontData.ts',
);
const base64 = fs.readFileSync(source).toString('base64');
fs.writeFileSync(
  target,
  `// Generated by scripts/gen-font.js from assets/fonts/LiberationSans-Subset.ttf.\n` +
    `// Liberation Sans — SIL Open Font License 1.1 (assets/fonts/OFL.txt).\n` +
    `export const UNICODE_FONT_BASE64 =\n  '${base64}';\n`,
);
